begin;
create temporary table sp_test_ids(a uuid,b uuid,ra uuid,rb uuid) on commit drop;
insert into sp_test_ids values(gen_random_uuid(),gen_random_uuid(),gen_random_uuid(),gen_random_uuid());
grant select on sp_test_ids to authenticated;
create temporary table sp_test_results(test text,expected integer,actual integer,passed boolean) on commit drop;
grant select,insert on sp_test_results to authenticated;
insert into auth.users(id,email) select a,'fixture-a-'||a||'@example.invalid' from sp_test_ids union all select b,'fixture-b-'||b||'@example.invalid' from sp_test_ids;
insert into public.skillproof_reports(id,user_id,payload) select ra,a,'{"fictionalData":true,"fixture":"A"}'::jsonb from sp_test_ids union all select rb,b,'{"fictionalData":true,"fixture":"B"}'::jsonb from sp_test_ids;
select set_config('request.jwt.claim.sub',(select a::text from sp_test_ids),true);
set local role authenticated;
insert into sp_test_results select 'A reads own report',1,count(*)::int,count(*)=1 from public.skillproof_reports where id=(select ra from sp_test_ids);
insert into sp_test_results select 'A cannot read B report by known ID',0,count(*)::int,count(*)=0 from public.skillproof_reports where id=(select rb from sp_test_ids);
reset role;
select set_config('request.jwt.claim.sub',(select b::text from sp_test_ids),true);
set local role authenticated;
insert into sp_test_results select 'B reads own report',1,count(*)::int,count(*)=1 from public.skillproof_reports where id=(select rb from sp_test_ids);
insert into sp_test_results select 'B cannot read A report by known ID',0,count(*)::int,count(*)=0 from public.skillproof_reports where id=(select ra from sp_test_ids);
insert into sp_test_results select 'B unfiltered list excludes A report',0,count(*)::int,count(*)=0 from public.skillproof_reports where user_id=(select a from sp_test_ids);
reset role;
select * from sp_test_results order by test;
rollback;